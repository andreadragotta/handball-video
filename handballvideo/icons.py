_SIZES = (16, 20, 24, 32, 40, 48, 64)


def _pixmap(name: str, color: str, size: int) -> QPixmap:
    svg = _SVG.format(_PATHS[name]).replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    pm = QPixmap(size, size)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p)
    p.end()
    return pm


@lru_cache(maxsize=None)
def icon(name: str, color: str = ICON_COLOR) -> QIcon:
    ic = QIcon()
    for size in _SIZES:
        ic.addPixmap(_pixmap(name, color, size), QIcon.Mode.Normal)
        ic.addPixmap(_pixmap(name, DISABLED_COLOR, size), QIcon.Mode.Disabled)
    return ic
